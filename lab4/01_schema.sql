BEGIN;

-- E1.
CREATE TABLE product_category (
    category_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_category_id integer REFERENCES product_category (category_id),
    category_name char(50) NOT NULL UNIQUE,
    description text,
    CHECK (parent_category_id <> category_id)
);

-- E2.
CREATE TABLE product (
    sku char(20) PRIMARY KEY,
    category_id integer NOT NULL REFERENCES product_category (category_id),
    tracking_method char(20) NOT NULL,
    product_name varchar(100) NOT NULL UNIQUE,
    status varchar(30) NOT NULL
);

-- E3.
CREATE TABLE product_attribute (
    attribute_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id integer NOT NULL REFERENCES product_category (category_id),
    attribute_name varchar(100) NOT NULL,
    value_type varchar(30) NOT NULL,
    unit varchar(20),
    is_required boolean NOT NULL
);

-- E4.
CREATE TABLE product_attribute_value (
    sku char(20) REFERENCES product (sku) ON DELETE CASCADE,
    attribute_id integer REFERENCES product_attribute (attribute_id),
    attribute_value text NOT NULL,
    unit varchar(20),
    PRIMARY KEY (sku, attribute_id)
);

-- E5.
CREATE TABLE supplier (
    supplier_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inn varchar(12) NOT NULL UNIQUE CHECK (inn ~ '^([0-9]{10}|[0-9]{12})$'),
    supplier_name varchar(100) NOT NULL,
    requisites text,
    contact_details varchar(255),
    status varchar(30) NOT NULL
);

-- E6.
CREATE TABLE supply_contract (
    contract_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id integer NOT NULL REFERENCES supplier (supplier_id),
    signed_on date NOT NULL,
    valid_from date NOT NULL,
    valid_to date,
    terms text,
    status varchar(30) NOT NULL,
    UNIQUE (contract_id, supplier_id),
    CHECK (valid_to >= valid_from)
);

-- E7.
CREATE TABLE purchase_price (
    contract_id integer REFERENCES supply_contract (contract_id),
    sku char(20) REFERENCES product (sku),
    valid_from date,
    valid_to date,
    amount numeric(12,2) NOT NULL CHECK (amount >= 0),
    currency char(3) NOT NULL,
    PRIMARY KEY (contract_id, sku, valid_from),
    CHECK (valid_to >= valid_from)
);

-- E18. 
CREATE TABLE store (
    store_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_name varchar(100) NOT NULL UNIQUE,
    address varchar(200) NOT NULL,
    region varchar(50) NOT NULL,
    status varchar(30) NOT NULL
);

-- E8.
CREATE TABLE store_request (
    request_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id integer NOT NULL REFERENCES store (store_id),
    requested_at timestamp NOT NULL,
    applicant varchar(100) NOT NULL,
    request_contents text NOT NULL,
    status varchar(30) NOT NULL,
    responsible_person varchar(100),
    UNIQUE (request_id, store_id)
);

-- E9.
CREATE TABLE delivery (
    contract_id integer,
    delivery_no integer,
    supplier_id integer NOT NULL REFERENCES supplier (supplier_id),
    received_on date NOT NULL,
    responsible_person varchar(100) NOT NULL,
    status varchar(30) NOT NULL,
    PRIMARY KEY (contract_id, delivery_no),
    FOREIGN KEY (contract_id, supplier_id)
        REFERENCES supply_contract (contract_id, supplier_id)
);

-- E10.
CREATE TABLE delivery_allocation (
    allocation_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id integer NOT NULL REFERENCES store (store_id),
    request_id integer NOT NULL,
    contract_id integer NOT NULL,
    delivery_no integer NOT NULL,
    allocated_on date NOT NULL,
    status varchar(30) NOT NULL,
    FOREIGN KEY (request_id, store_id) REFERENCES store_request (request_id, store_id),
    FOREIGN KEY (contract_id, delivery_no) REFERENCES delivery (contract_id, delivery_no)
);

-- E23.
CREATE TABLE delivery_allocation_item (
    allocation_id integer REFERENCES delivery_allocation (allocation_id) ON DELETE CASCADE,
    sku char(20) REFERENCES product (sku),
    quantity integer NOT NULL CHECK (quantity > 0),
    PRIMARY KEY (allocation_id, sku)
);

-- E11.
CREATE TABLE product_instance (
    serial_number integer PRIMARY KEY,
    sku char(20) NOT NULL REFERENCES product (sku),
    received_on date NOT NULL,
    current_location text NOT NULL,
    status varchar(30) NOT NULL,
    UNIQUE (serial_number, sku)
);

-- E12.
CREATE TABLE kit (
    kit_sku char(20) REFERENCES product (sku),
    composition_version integer CHECK (composition_version > 0),
    kit_name varchar(100) NOT NULL,
    formed_on date NOT NULL,
    status varchar(30) NOT NULL,
    PRIMARY KEY (kit_sku, composition_version)
);

-- E13.
CREATE TABLE kit_component (
    kit_sku char(20),
    composition_version integer,
    component_sku char(20) REFERENCES product (sku),
    quantity integer NOT NULL CHECK (quantity > 0),
    component_order varchar(50),
    is_required boolean NOT NULL,
    allowed_substitutions text,
    PRIMARY KEY (kit_sku, composition_version, component_sku),
    FOREIGN KEY (kit_sku, composition_version)
        REFERENCES kit (kit_sku, composition_version) ON DELETE CASCADE,
    CHECK (kit_sku <> component_sku)
);

-- E14.
CREATE TABLE retail_price (
    sku char(20) REFERENCES product (sku),
    region char(40),
    valid_from date,
    valid_to date,
    amount numeric(12,2) NOT NULL CHECK (amount >= 0),
    currency char(3) NOT NULL,
    PRIMARY KEY (sku, region, valid_from),
    CHECK (valid_to >= valid_from)
);

-- E15. 
CREATE TABLE sale (
    sale_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id integer NOT NULL REFERENCES store (store_id),
    sold_at timestamp NOT NULL,
    customer varchar(100),
    total_amount numeric(12,2) NOT NULL CHECK (total_amount >= 0),
    status varchar(30) NOT NULL
);

-- E21.
CREATE TABLE sale_item (
    sale_id integer REFERENCES sale (sale_id) ON DELETE CASCADE,
    line_no integer CHECK (line_no > 0),
    serial_number integer,
    sku char(20) NOT NULL REFERENCES product (sku),
    quantity integer NOT NULL CHECK (quantity > 0),
    unit_price numeric(12,2) NOT NULL CHECK (unit_price >= 0),
    PRIMARY KEY (sale_id, line_no),
    FOREIGN KEY (serial_number, sku) REFERENCES product_instance (serial_number, sku),
    CHECK (serial_number IS NULL OR quantity = 1)
);

-- E16.
CREATE TABLE sale_return (
    return_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id integer NOT NULL REFERENCES sale (sale_id),
    store_id integer NOT NULL REFERENCES store (store_id),
    returned_at timestamp NOT NULL,
    reason text NOT NULL,
    responsible_person varchar(100) NOT NULL,
    status varchar(30) NOT NULL,
    total_amount numeric(12,2) NOT NULL CHECK (total_amount >= 0),
    UNIQUE (return_id, sale_id)
);

-- E22.
CREATE TABLE return_item (
    return_id integer,
    line_no integer CHECK (line_no > 0),
    sale_id integer NOT NULL,
    sale_line_no integer NOT NULL,
    quantity integer NOT NULL CHECK (quantity > 0),
    unit_price numeric(12,2) NOT NULL CHECK (unit_price >= 0),
    PRIMARY KEY (return_id, line_no),
    FOREIGN KEY (return_id, sale_id)
        REFERENCES sale_return (return_id, sale_id) ON DELETE CASCADE,
    FOREIGN KEY (sale_id, sale_line_no) REFERENCES sale_item (sale_id, line_no)
);

-- E17.
CREATE TABLE warranty_claim (
    claim_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    serial_number integer NOT NULL REFERENCES product_instance (serial_number),
    customer varchar(100) NOT NULL,
    claimed_on date NOT NULL,
    fault_description text NOT NULL,
    warranty_terms text,
    status varchar(30) NOT NULL,
    decision text
);

-- E19.
CREATE TABLE repair_record (
    claim_id integer REFERENCES warranty_claim (claim_id),
    record_no integer,
    repaired_on date NOT NULL,
    work_description text NOT NULL,
    result text,
    PRIMARY KEY (claim_id, record_no)
);

-- E20.
CREATE TABLE discrepancy_report (
    report_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_id integer NOT NULL REFERENCES sale_return (return_id),
    reported_on date NOT NULL,
    sold_serial_number varchar(50) NOT NULL,
    returned_serial_number varchar(50) NOT NULL,
    discrepancy_description text NOT NULL
);

COMMIT;
